"""Artifact storage contracts and a safe local development implementation.

The local adapter is for development and tests. Production deployments should
use a durable private object store through an adapter implementing ArtifactStore.
Artifact keys are generated by the application; user filenames are metadata,
never filesystem paths.
"""

from __future__ import annotations

import hashlib
import os
import tempfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import BinaryIO, Protocol


@dataclass(frozen=True, slots=True)
class StoredArtifact:
    key: str
    sha256: str
    size_bytes: int


class ArtifactStore(Protocol):
    """Storage interface shared by local and future object-store adapters."""

    def put(self, key: str, source: BinaryIO, *, max_bytes: int) -> StoredArtifact: ...

    def get_path(self, key: str) -> Path: ...

    def delete(self, key: str) -> None: ...

    def exists(self, key: str) -> bool: ...


def validate_artifact_key(key: str) -> PurePosixPath:
    """Reject absolute paths, traversal, empty segments, and platform separators."""
    if not key or "\x00" in key or "\\" in key:
        raise ValueError("Invalid artifact key.")
    path = PurePosixPath(key)
    if path.is_absolute() or any(part in {"", ".", ".."} for part in path.parts):
        raise ValueError("Invalid artifact key.")
    if not path.parts or ":" in path.parts[0]:
        raise ValueError("Invalid artifact key.")
    return path


class LocalArtifactStore:
    """Content-hashing, size-limited filesystem adapter for local development."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).expanduser().resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _target(self, key: str) -> Path:
        relative = validate_artifact_key(key)
        target = self.root.joinpath(*relative.parts)
        # Resolve existing parent components to reject symlink escapes.
        resolved_parent = target.parent.resolve()
        if not resolved_parent.is_relative_to(self.root):
            raise ValueError("Artifact key escapes the configured storage root.")
        return target

    def put(self, key: str, source: BinaryIO, *, max_bytes: int) -> StoredArtifact:
        if max_bytes < 1:
            raise ValueError("max_bytes must be positive.")
        target = self._target(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        # Re-check after directory creation in case a parent was replaced.
        target = self._target(key)
        if target.exists():
            raise FileExistsError("Artifact keys are immutable and cannot be overwritten.")

        digest = hashlib.sha256()
        size = 0
        temp_name: str | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="wb", dir=target.parent, prefix=".upload-", delete=False
            ) as temporary:
                temp_name = temporary.name
                while chunk := source.read(1024 * 1024):
                    size += len(chunk)
                    if size > max_bytes:
                        raise ValueError("Artifact exceeds the configured size limit.")
                    digest.update(chunk)
                    temporary.write(chunk)
                temporary.flush()
                os.fsync(temporary.fileno())

            # Hard-link creation is atomic and refuses to replace an existing key.
            os.link(temp_name, target)
            os.unlink(temp_name)
            temp_name = None
        finally:
            if temp_name is not None:
                try:
                    os.unlink(temp_name)
                except FileNotFoundError:
                    pass

        return StoredArtifact(key=key, sha256=digest.hexdigest(), size_bytes=size)

    def get_path(self, key: str) -> Path:
        target = self._target(key)
        if not target.is_file():
            raise FileNotFoundError(key)
        # Resolve the final path too; reject a malicious symlink target.
        resolved = target.resolve(strict=True)
        if not resolved.is_relative_to(self.root):
            raise ValueError("Artifact path escapes the configured storage root.")
        return resolved

    def delete(self, key: str) -> None:
        target = self._target(key)
        try:
            target.unlink()
        except FileNotFoundError:
            return

    def exists(self, key: str) -> bool:
        try:
            return self.get_path(key).is_file()
        except FileNotFoundError:
            return False
